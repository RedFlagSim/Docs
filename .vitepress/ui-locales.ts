export type UiLocale = keyof typeof uiCopies
export const uiFor = (locale: string) => uiCopies[(locale === 'root' ? 'en' : locale) as UiLocale] ?? uiCopies.en
export const uiForLanguage = (lang: string) => uiFor(({ 'en-US': 'en', 'zh-CN': 'zh', 'zh-TW': 'zh-tw', 'ja-JP': 'ja', 'ko-KR': 'ko', 'ru-RU': 'ru', 'de-DE': 'de', 'es-ES': 'es', 'fr-FR': 'fr' } as Record<string, string>)[lang] ?? 'en')
export function localeUi(locale: string): DefaultTheme.Config {
  const t = uiFor(locale)
  return {
    notFound: { title: t.notFoundTitle, quote: t.notFoundQuote, linkLabel: t.home, linkText: t.home },
    outline: { label: t.outline }, docFooter: { prev: t.prev, next: t.next },
    darkModeSwitchLabel: t.appearance, lightModeSwitchTitle: t.light, darkModeSwitchTitle: t.dark,
    sidebarMenuLabel: t.menu, returnToTopLabel: t.top, langMenuLabel: t.language, skipToContentLabel: t.skip
  }
}
export const searchLocales = Object.fromEntries(Object.keys(uiCopies).map(locale => {
  const t = uiFor(locale)
  return [locale === 'en' ? 'root' : locale, { translations: {
    button: { buttonText: t.search, buttonAriaLabel: t.search },
    modal: { displayDetails: t.details, resetButtonTitle: t.reset, backButtonTitle: t.back, noResultsText: t.noResults,
      footer: { selectText: t.select, selectKeyAriaLabel: t.enter, navigateText: t.navigate, navigateUpKeyAriaLabel: t.up, navigateDownKeyAriaLabel: t.down, closeText: t.close, closeKeyAriaLabel: t.escape }
    }
  }}]
}))
